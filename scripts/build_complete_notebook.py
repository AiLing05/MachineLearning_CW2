"""Combine the individual member notebooks into one complete project notebook.

Usage (from the project folder):
    python scripts/build_complete_notebook.py
    jupyter nbconvert --to notebook --execute --inplace notebooks/00_complete_project.ipynb

The member notebooks stay the source of truth; re-run this script after any of
them change. Outputs are cleared so the combined notebook is always re-executed.
"""
from __future__ import annotations

from pathlib import Path

import nbformat

ROOT = Path(__file__).resolve().parents[1]
NOTEBOOKS = ROOT / "notebooks"
OUTPUT = NOTEBOOKS / "00_complete_project.ipynb"

SECTIONS = [
    ("01_member1_eda_preprocessing.ipynb",
     "Parts A–C: Problem Definition, EDA and Data Preparation (Member 1)"),
    ("02_member2_logistic_regression.ipynb",
     "Part D: Logistic Regression Baseline (Member 2)"),
    ("03_member2_decision_tree.ipynb",
     "Part D: Decision Tree Baseline (Member 2)"),
    ("04_member2_logistic_optimisation.ipynb",
     "Part E: Logistic Regression Optimisation (Member 2)"),
    ("05_member2_decision_tree_optimisation.ipynb",
     "Part E: Decision Tree Optimisation (Member 2)"),
    ("06_member3_random_forest.ipynb",
     "Parts D–F: Random Forest and Soft Voting Ensemble (Member 3)"),
    ("07_member4_evaluation.ipynb",
     "Part G: Model Evaluation and Comparative Analysis (Member 4)"),
]

INTRO = """# Heart Disease Prediction Using Health Indicators – Complete Project Notebook

**6001CMD Machine Learning Group Assignment**

Comparative machine learning and ensemble learning on the BRFSS 2015 Heart Disease
Health Indicators dataset (253,680 records, 21 features, binary target
`HeartDiseaseorAttack`).

This notebook is generated by `scripts/build_complete_notebook.py` from the individual
member notebooks and runs the whole project from start to finish:

| Section | Content | Member |
|---|---|---|
| 1 | Problem definition, EDA, data preparation and shared train/test split | Member 1 |
| 2–5 | Logistic Regression and Decision Tree: baselines and optimisation | Member 2 |
| 6 | Random Forest, model selection and soft voting ensemble | Member 3 |
| 7 | Final test-set evaluation and comparison of all four models | Member 4 |

All models use the same hold-out test set and the same five cross-validation folds.
The test set is only used in Section 7, after every model has been frozen."""


def build() -> nbformat.NotebookNode:
    combined = nbformat.v4.new_notebook()
    combined.cells.append(nbformat.v4.new_markdown_cell(INTRO))
    for number, (filename, title) in enumerate(SECTIONS, start=1):
        source = nbformat.read(NOTEBOOKS / filename, as_version=4)
        combined.cells.append(nbformat.v4.new_markdown_cell(
            f"---\n# Section {number}. {title}\n\n*Source notebook: `notebooks/{filename}`*"))
        for cell in source.cells:
            if cell.cell_type == "code":
                new = nbformat.v4.new_code_cell(cell.source)
            elif cell.cell_type == "markdown":
                new = nbformat.v4.new_markdown_cell(cell.source)
                if "attachments" in cell:
                    new["attachments"] = cell["attachments"]
            else:
                continue
            combined.cells.append(new)
    combined.metadata["kernelspec"] = {
        "name": "python3", "display_name": "Python 3", "language": "python"}
    combined.metadata["language_info"] = {"name": "python"}
    return combined


if __name__ == "__main__":
    nbformat.write(build(), OUTPUT)
    print(f"Wrote {OUTPUT.relative_to(ROOT)}")
